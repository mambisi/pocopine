/// RFC-096 S4 — the explicit JS interop shim: mint (once, cached)
/// a `js_sys::Proxy` over `scope_id` whose get/set traps delegate
/// to the shared read/write mirrors, for foreign JS that must
/// touch component state directly. Everything pocopine ships
/// works without it; nothing in the framework calls it. Returns
/// `None` when the scope is gone.
pub fn js_bridge(scope_id: ScopeId) -> Option<JsValue> {
    if let Some(cached) = BRIDGES.with(|b| b.borrow().get(&scope_id).cloned()) {
        return Some(cached);
    }
    let scope = Scope::find(scope_id)?;
    let proxy = scope.into_proxy();
    BRIDGES.with(|b| {
        b.borrow_mut().insert(scope_id, proxy.clone());
    });
    Some(proxy)
}

impl Scope {
    fn mint_proxy(scope_id: ScopeId, state: &Rc<RefCell<dyn ComponentState>>) -> JsValue {
        #[cfg(any(debug_assertions, feature = "devtools"))]
        PROXIES_MINTED.with(|c| c.set(c.get() + 1));
        let target = Object::new();
        let handler = Object::new();
        let state_for_get = state.clone();
        let state_for_set = state.clone();

        let get_closure = Closure::wrap(Box::new(
            move |_target: JsValue, key: JsValue, _receiver: JsValue| -> JsValue {
                let Some(key_str) = key.as_string() else {
                    return JsValue::UNDEFINED;
                };
                // RFC-096 S2 — the trap delegates to the shared
                // read mirror (loop locals + magics + tracked
                // field read in one place).
                read_scope_key_with(scope_id, &state_for_get, &key_str)
            },
        )
            as Box<dyn Fn(JsValue, JsValue, JsValue) -> JsValue>);

        let set_closure = Closure::wrap(Box::new(
            move |_target: JsValue, key: JsValue, value: JsValue, _receiver: JsValue| -> bool {
                let Some(key_str) = key.as_string() else {
                    return false;
                };
                // RFC-096 S1 — the trap delegates to the shared
                // write mirror; one implementation for trap and
                // proxy-free writes alike.
                write_field_tracked(scope_id, &state_for_set, &key_str, value);
                true
            },
        )
            as Box<dyn Fn(JsValue, JsValue, JsValue, JsValue) -> bool>);

        Reflect::set(
            &handler,
            &"get".into(),
            get_closure.as_ref().unchecked_ref(),
        )
        .expect("set get trap");
        Reflect::set(
            &handler,
            &"set".into(),
            set_closure.as_ref().unchecked_ref(),
        )
        .expect("set set trap");

        // Pin the two closures in the per-scope side-table. The
        // handler `Object` holds their JS function pointers; we
        // hold the Rust `Closure` wrappers so the `Box<dyn Fn>`
        // they own is dropped when `Scope::remove` runs. Previously
        // a `.forget()` call leaked both boxes for the life of the
        // process.
        PROXY_CLOSURES.with(|m| {
            m.borrow_mut().entry(scope_id).or_default().extend([
                Box::new(get_closure) as Box<dyn Any>,
                Box::new(set_closure) as Box<dyn Any>,
            ]);
        });

        Proxy::new(&target, &handler).into()
    }

    /// Invoke a handler by name. Mutates Rust state directly, then
    /// runs the RFC-095 per-field dirty sweep: only fields whose
    /// fingerprints moved get their cache slot dropped and their
    /// subscribers triggered.
    ///
    /// Browser APIs can synchronously dispatch an event back into the same
    /// component while its first handler still owns `&mut state` (`focus()` is
    /// the common case). Such same-scope re-entry joins the shared callback
    /// FIFO instead of attempting an aliased `RefCell::borrow_mut`. Nested
    /// handlers for different scopes may remain synchronous, but all share
    /// one outer safe point: queued work drains only after every component
    /// borrow and dirty sweep has finished. A queued invocation returns
    /// `undefined` to its immediate caller because its real result cannot
    /// exist until that caller unwinds.
    pub fn invoke(&self, key: &str, args: &Array) -> JsValue {
        if crate::component_callback::scope_is_active(self.id) {
            let scope = self.clone();
            let key = key.to_string();
            // The nested call returns before it executes, so retain the values
            // as they existed at the call site instead of only cloning the JS
            // Array handle (which the caller could mutate while unwinding).
            let args = args.slice(0, args.length());
            crate::defer_component_callback_for(self.id, move || {
                let _ = scope.invoke(&key, &args);
            });
            return JsValue::UNDEFINED;
        }

        let _frame = crate::ComponentCallbackFrame::for_scope(self.id);
        self.invoke_now(key, args)
    }

    /// One non-reentrant handler invocation. [`Scope::invoke`] owns the
    /// component callback frame and same-scope deferral around this method.
    fn invoke_now(&self, key: &str, args: &Array) -> JsValue {
        let prev = CURRENT_SCOPE_ID.with(|c| c.replace(Some(self.id)));
        #[cfg(feature = "devtools")]
        let start = crate::devtools::ring::now_ms_for_scope();
        // RFC-097 §3.3 — a `&self` handler provably cannot mutate state
        // (macro-enforced receiver + the interior-mutability field
        // rejection), so skip the whole sweep + model-write bracket:
        // no fingerprints, no model snapshot, no trigger. Just bind the
        // scope and run it. (`invoke` still takes `&mut self` as the
        // type-erased dispatch entry; the user method is `&self`.)
        let readonly = self.state.borrow().is_readonly_handler(key);
        let out = if readonly {
            let out = self.state.borrow_mut().invoke(key, args);
            CURRENT_SCOPE_ID.with(|c| c.set(prev));
            out
        } else {
            let sweep = DirtySweep::begin(self.id, &self.state);
            let out = crate::model_runtime::with_scope_write(
                self.id,
                crate::model_runtime::WriteOrigin::LocalHandler,
                || self.state.borrow_mut().invoke(key, args),
            );
            CURRENT_SCOPE_ID.with(|c| c.set(prev));
            match sweep {
                Some(sweep) => sweep.finish(&self.state),
                None => {
                    // Handler may have mutated arbitrary fields through
                    // `&mut self` and we couldn't snapshot — drop the
                    // whole cache and trigger every tracked key.
                    invalidate_field_cache(self.id);
                    trigger_scope(self.id);
                }
            }
            out
        };
        // Devtools hook — fired after trigger_scope so any effect
        // runs scheduled by this handler are visible on the timeline
        // with a seq > this handler's.
        #[cfg(feature = "devtools")]
        {
            let dur = std::time::Duration::from_micros(
                ((crate::devtools::ring::now_ms_for_scope() - start).max(0.0) * 1000.0) as u64,
            );
            crate::devtools::hooks::fire_handler_invoke(self.id, key, args, dur);
        }
        out
    }
}

/// Drop every cached field `JsValue` for `scope_id`. Called from
/// `Handle::update` (which doesn't know which fields the closure
/// touched), and from `Scope::invoke`. Targeted op APIs
/// (`patch_list_at` and friends) deliberately do NOT call this —
/// they keep the cache valid by patching it in lockstep with
/// the Rust mutation, which is the whole point of the API.
pub fn invalidate_field_cache(scope_id: ScopeId) {
    let patched = PATCHED.with(|f| f.borrow_mut().remove(&scope_id).unwrap_or_default());
    for sid in crate::reactive::interned_signal_ids(scope_id) {
        if patched.contains(&sid) {
            projection_confirm_patched(sid);
        } else {
            projection_invalidate(sid);
        }
    }
}

/// RFC-095 W2 — per-field dirty sweep around a `&mut self`
/// mutation (`Scope::invoke`, `Handle::update`).
///
/// [`DirtySweep::begin`] fingerprints every *observed* key — every
/// key interned for the scope (`reactive::tracked_keys`; RFC-096
/// S3: projection reads intern too, so this covers cached-but-
/// untracked keys) — via [`ComponentState::field_fingerprint`],
/// entirely Rust-side. After the mutation, [`DirtySweep::finish`]
/// re-fingerprints and:
///
/// - **bumps versions** only on the changed keys' projections (a
///   key surgically patched via `patch_*_inline` gets its
///   projection re-stamped to the new version instead — the patch
///   wrote it correctly; the PATCHED mark is consumed here),
/// - **triggers** only the changed keys' subscribers.
///
/// A key whose fingerprint is unknown (`None` — computed fields,
/// flatten leaves, non-field keys) is treated as changed, which
/// reproduces the pre-sweep behavior for exactly those keys. A
/// scope whose state is mid-borrow (re-entrant invoke) yields
/// `None` from `begin`; callers fall back to the blanket
/// invalidate + scope-wide trigger.
pub(crate) struct DirtySweep {
    scope_id: ScopeId,
    keys: Vec<crate::reactive::Key>,
    before: Vec<Option<u64>>,
    /// RFC-095 W2b — O(1) length probes captured alongside the
    /// fingerprints. A probe that moves (or flips `Some`/`None`)
    /// proves the field changed without re-hashing its contents
    /// — the whole win for `rows = vec![...10K]`-style writes.
    lens_before: Vec<Option<u64>>,
}

impl DirtySweep {
    pub(crate) fn begin(
        scope_id: ScopeId,
        state: &Rc<RefCell<dyn ComponentState>>,
    ) -> Option<DirtySweep> {
        let state = state.try_borrow().ok()?;
        // RFC-096 S3 — interned keys cover both tracked reads and
        // projection-only reads (projection access interns the
        // signal), so the old FIELD_CACHE union is unnecessary.
        let keys = crate::reactive::tracked_keys(scope_id);
        let before = keys
            .iter()
            .map(|k| {
                count_fingerprint();
                state.field_fingerprint(k.as_ref())
            })
            .collect();
        let lens_before = keys
            .iter()
            .map(|k| state.field_quick_len(k.as_ref()))
            .collect();
        Some(DirtySweep {
            scope_id,
            keys,
            before,
            lens_before,
        })
    }

    pub(crate) fn finish(self, state: &Rc<RefCell<dyn ComponentState>>) {
        let Ok(state_ref) = state.try_borrow() else {
            // Mutation left the state borrowed (shouldn't happen —
            // the handler returned) — degrade to the blanket path.
            invalidate_field_cache(self.scope_id);
            crate::reactive::trigger_scope(self.scope_id);
            return;
        };
        let mut changed: Vec<crate::reactive::Key> = Vec::new();
        for ((k, before), len_before) in self
            .keys
            .iter()
            .zip(self.before.iter())
            .zip(self.lens_before.iter())
        {
            // Length probe first: a moved (or flipped) probe is
            // proof of change with no content hash. Equal probes
            // prove nothing (same-length edits) — fall through.
            let len_after = state_ref.field_quick_len(k.as_ref());
            if *len_before != len_after {
                changed.push(k.clone());
                continue;
            }
            count_fingerprint();
            let after = state_ref.field_fingerprint(k.as_ref());
            let unchanged = matches!((before, &after), (Some(b), Some(a)) if b == a);
            if !unchanged {
                changed.push(k.clone());
            }
        }
        drop(state_ref);
        // Consume the patched marks — projections the `patch_*`
        // APIs kept correct survive via a version re-stamp; every
        // other changed projection is invalidated by version bump.
        let patched = PATCHED.with(|f| f.borrow_mut().remove(&self.scope_id).unwrap_or_default());
        if changed.is_empty() {
            return;
        }
        for k in &changed {
            let sid = crate::reactive::ensure_field_signal(self.scope_id, k.as_ref());
            if patched.contains(&sid) {
                projection_confirm_patched(sid);
            } else {
                projection_invalidate(sid);
            }
        }
        for k in &changed {
            crate::reactive::trigger(self.scope_id, k.as_ref());
        }
    }
}

/// Drop one field's cache slot. Call this from inside a
/// `&mut self` handler after a Rust-side mutation when you DON'T
/// want a full state re-serialise on the next read but also can't
/// patch the JS cache surgically (e.g. structural reshape, length
/// change). Reactivity does NOT fire here — call `trigger` (or
/// the caller's `Handle::update` boundary) for that.
pub fn invalidate_field(scope_id: ScopeId, field: &str) {
    projection_invalidate(crate::reactive::ensure_field_signal(scope_id, field));
}

/// Patch one element of a `Vec<T>`-style field's cached
/// `JsValue` against the *current* scope (resolved via
/// `current_scope_id`). Designed to be called from inside a
/// `&mut self` handler after a Rust-side mutation:
///
/// ```ignore
/// pub fn touch_row(&mut self, idx: usize) {
///     self.rows[idx].label.push_str(" !!!");
///     pocopine::scope::patch_list_at_inline(
///         "rows", idx, &self.rows[idx],
///     );
/// }
/// ```
///
/// Reactivity fires for `field` on the current scope id. Unlike
/// `Handle::update`'s blanket `trigger_scope`, only effects
/// subscribed to `field` re-evaluate. The cached `JsValue` is
/// patched in place via `Reflect::set` so the live JS Array
/// readers (e.g. a `pp-for` reconcile) see the same Array
/// identity with one updated cell — Object identities for
/// every other row stay stable.
///
/// No-op (still fires reactivity) when:
///
/// - no scope is currently set (called outside a handler),
/// - the field has never been read by a JS effect (cache empty),
/// - the cached value isn't object-shaped (e.g. raw scalar field).
pub fn patch_list_at_inline<T: serde::Serialize>(field: &str, idx: usize, row: &T) {
    let Some(sid) = current_scope_id() else {
        return;
    };
    let cached = projection_read(sid, field);
    if let Some(arr) = cached {
        let patched = arr.is_object()
            && serde_wasm_bindgen::to_value(row)
                .ok()
                .is_some_and(|new_js| {
                    Reflect::set(&arr, &(idx as u32).into(), &new_js).unwrap_or(false)
                });
        finish_inline_patch(sid, field, patched);
    }
    crate::reactive::trigger(sid, field);
}

/// Patch several elements of a cached JS Array and trigger once.
/// This is the bulk sibling of [`patch_list_at_inline`] for handlers
/// such as "update every 10th row": it preserves object identity for
/// untouched rows without paying one reactive dispatch per changed row.
pub fn patch_list_indices_inline<T: serde::Serialize>(field: &str, patches: &[(usize, &T)]) {
    let Some(sid) = current_scope_id() else {
        return;
    };
    let cached = projection_read(sid, field);
    if let Some(arr) = cached {
        let mut patched = arr.is_object();
        if patched {
            for (idx, row) in patches {
                let ok = serde_wasm_bindgen::to_value(row)
                    .ok()
                    .is_some_and(|new_js| {
                        Reflect::set(&arr, &(*idx as u32).into(), &new_js).unwrap_or(false)
                    });
                patched &= ok;
            }
        }
        finish_inline_patch(sid, field, patched);
    }
    crate::reactive::trigger(sid, field);
}

fn keep_field_fresh(scope_id: ScopeId, field: &str) {
    // RFC-096 S3 — mark the projection as patch-maintained: the
    // post-handler sweep re-stamps it to the new version instead
    // of dropping it.
    let sid = crate::reactive::ensure_field_signal(scope_id, field);
    PATCHED.with(|f| {
        f.borrow_mut().entry(scope_id).or_default().insert(sid);
    });
}

fn finish_inline_patch(scope_id: ScopeId, field: &str, patched: bool) {
    if patched {
        keep_field_fresh(scope_id, field);
    } else {
        // A partial or rejected JS mutation is not authoritative. Drop the
        // projection so the next read serializes the Rust field again.
        invalidate_field(scope_id, field);
    }
}

/// Swap two indices inside a cached JS Array for a Vec-like field.
/// Call from inside a handler after swapping the Rust Vec. This keeps
/// existing row object identities intact, so keyed `pp-for` can avoid
/// re-stringifying unchanged rows on the follow-up reconcile.
pub fn swap_list_indices_inline(field: &str, a: usize, b: usize) {
    let Some(sid) = current_scope_id() else {
        return;
    };
    let cached = projection_read(sid, field);
    if let Some(arr) = cached {
        let patched = if arr.is_object() {
            let a_key = JsValue::from_f64(a as f64);
            let b_key = JsValue::from_f64(b as f64);
            match (Reflect::get(&arr, &a_key), Reflect::get(&arr, &b_key)) {
                (Ok(a_val), Ok(b_val)) => {
                    Reflect::set(&arr, &a_key, &b_val).unwrap_or(false)
                        && Reflect::set(&arr, &b_key, &a_val).unwrap_or(false)
                }
                _ => false,
            }
        } else {
            false
        };
        finish_inline_patch(sid, field, patched);
    }
    crate::reactive::trigger(sid, field);
}

/// Remove one element from a cached JS Array for a Vec-like field,
/// preserving object identity for every surviving row. Call from
/// inside a handler after removing the same index from the Rust Vec.
pub fn remove_list_at_inline(field: &str, idx: usize) {
    let Some(sid) = current_scope_id() else {
        return;
    };
    let cached = projection_read(sid, field);
    if let Some(arr) = cached {
        let patched = if arr.is_object() {
            let array = js_sys::Array::from(&arr);
            let len = array.length();
            let idx = idx as u32;
            if idx < len
                && let Ok(splice) = Reflect::get(&arr, &JsValue::from_str("splice")).and_then(|v| {
                    v.dyn_into::<Function>()
                        .map_err(|_| JsValue::from_str("Array.splice is not callable"))
                })
            {
                splice
                    .call2(
                        &arr,
                        &JsValue::from_f64(idx as f64),
                        &JsValue::from_f64(1.0),
                    )
                    .is_ok()
            } else {
                false
            }
        } else {
            false
        };
        finish_inline_patch(sid, field, patched);
    }
    crate::reactive::trigger(sid, field);
}

/// Append serialized rows into a cached JS Array for a Vec-like field.
/// Call from inside a handler after extending the Rust Vec. Existing
/// JS row objects remain in place; only the appended range is
/// serialized.
pub fn append_list_inline<T: serde::Serialize>(field: &str, start_idx: usize, rows: &[T]) {
    let Some(sid) = current_scope_id() else {
        return;
    };
    let cached = projection_read(sid, field);
    if let Some(arr) = cached {
        let mut patched = arr.is_object();
        if patched {
            for (offset, row) in rows.iter().enumerate() {
                let ok = serde_wasm_bindgen::to_value(row)
                    .ok()
                    .is_some_and(|new_js| {
                        Reflect::set(&arr, &((start_idx + offset) as u32).into(), &new_js)
                            .unwrap_or(false)
                    });
                patched &= ok;
            }
        }
        finish_inline_patch(sid, field, patched);
    }
    crate::reactive::trigger(sid, field);
}

/// Prepend serialized rows into a cached JS Array for a Vec-like
/// field while preserving existing JS row object identities in the
/// shifted tail. Call from inside a handler after prepending the
/// Rust Vec.
pub fn prepend_list_inline<T: serde::Serialize>(field: &str, rows: &[T]) {
    let Some(sid) = current_scope_id() else {
        return;
    };
    let cached = projection_read(sid, field);
    if let Some(arr) = cached {
        let mut patched = arr.is_object();
        if patched {
            let array = js_sys::Array::from(&arr);
            let added = rows.len() as u32;
            let old_len = array.length();
            for idx in (0..old_len).rev() {
                let ok = Reflect::get(&arr, &idx.into()).ok().is_some_and(|value| {
                    Reflect::set(&arr, &(idx + added).into(), &value).unwrap_or(false)
                });
                patched &= ok;
            }
            for (idx, row) in rows.iter().enumerate() {
                let ok = serde_wasm_bindgen::to_value(row)
                    .ok()
                    .is_some_and(|new_js| {
                        Reflect::set(&arr, &(idx as u32).into(), &new_js).unwrap_or(false)
                    });
                patched &= ok;
            }
        }
        finish_inline_patch(sid, field, patched);
    }
    crate::reactive::trigger(sid, field);
}

/// Replace the entire cached `JsValue` for `field` against the
/// current scope. Fires per-field reactivity. Use this when a
/// structural change (push / swap / clear / length change) means
/// individual cell patching won't work — re-serialise the whole
/// field once, stash it, and trigger. Sister of
/// [`patch_list_at_inline`] for ops without per-index granularity.
pub fn replace_field_inline<T: serde::Serialize>(field: &str, value: &T) {
    let Some(sid) = current_scope_id() else {
        return;
    };
    match serde_wasm_bindgen::to_value(value) {
        Ok(new_js) => {
            projection_store(sid, field, new_js);
            keep_field_fresh(sid, field);
        }
        Err(_) => invalidate_field(sid, field),
    }
    crate::reactive::trigger(sid, field);
}

/// The scope whose handler is currently on the stack. `None` outside of a
/// handler invocation. Handlers use this to hand their id to an async task:
///
/// ```ignore
/// pub fn init(&mut self) {
///     let id = pocopine::current_scope_id().unwrap();
///     self.loading = true;
///     wasm_bindgen_futures::spawn_local(async move {
///         let post = api::get_post(1).await;
///         if let Some(scope) = Scope::find(id) {
///             scope.state.borrow_mut().set("title", /* ... */);
///             pocopine::reactive::trigger_scope(id);
///         }
///     });
/// }
/// ```
pub fn current_scope_id() -> Option<ScopeId> {
    CURRENT_SCOPE_ID.with(|c| c.get())
}

/// Run `f` with `CURRENT_SCOPE_ID` set to `id`, restoring the prior
/// value on exit. Used by [`crate::handle::Handle::update`] so
/// `dispatch!` / `this::<T>()` called from inside an async update
/// closure still sees its own scope. Also used internally by
/// [`Scope::invoke`].
pub fn with_current_scope_id<R>(id: ScopeId, f: impl FnOnce() -> R) -> R {
    let prev = CURRENT_SCOPE_ID.with(|c| c.replace(Some(id)));
    let out = f();
    CURRENT_SCOPE_ID.with(|c| c.set(prev));
    out
}

/// Set the current element for the duration of a directive call. The caller
/// is responsible for clearing it on exit.
pub fn with_current_el<R>(el: &Element, f: impl FnOnce() -> R) -> R {
    let prev = CURRENT_EL.with(|c| c.replace(Some(el.clone())));
    let out = f();
    CURRENT_EL.with(|c| *c.borrow_mut() = prev);
    out
}

/// The element the current directive is running against, if any.
pub fn current_el() -> Option<Element> {
    CURRENT_EL.with(|c| c.borrow().clone())
}

// A compact helper for callers that need to pull a scope out of the registry
// by id without importing the inner types.
pub fn invoke_handler(scope_id: ScopeId, key: &str, args: &Array) -> JsValue {
    match Scope::find(scope_id) {
        Some(s) => s.invoke(key, args),
        None => JsValue::UNDEFINED,
    }
}
