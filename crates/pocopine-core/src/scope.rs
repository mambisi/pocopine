//! Component scopes and the JS-`Proxy` bridge they expose to directives.
//!
//! A scope owns a `ComponentState` (macro-generated), a stable `ScopeId`, and
//! a `js_sys::Proxy` whose `get`/`set` traps plug into [`crate::reactive`] so
//! any directive that reads a field through the proxy gets auto-subscribed.

use std::any::Any;
use std::cell::RefCell;
use std::collections::HashMap;
use std::rc::Rc;

use js_sys::{Array, Function, Object, Proxy, Reflect};
use wasm_bindgen::JsValue;
use wasm_bindgen::closure::Closure;
use wasm_bindgen::prelude::*;
use web_sys::Element;

use crate::magics;
use crate::reactive::{ScopeId, SignalId, next_scope_id, track, trigger, trigger_scope};

/// Static HTML attributes are strings, but Pocopine has historically
/// coerced them before writing component props. The macro supplies this
/// narrow field-kind hint so the runtime can preserve numeric-looking
/// strings for `String` props while keeping number/bool ergonomics for
/// number/bool props.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum StaticPropKind {
    Auto,
    String,
    Bool,
    Number,
}

/// Implemented by components (generated by `#[component]` + `#[handlers]`).
pub trait ComponentState: 'static {
    /// Read a declared field as a JsValue (for proxy `get`).
    fn get(&self, key: &str) -> JsValue;

    /// Whether this state's `get` returns values worth caching in the
    /// per-signal projection store. Defaults to `true` for component
    /// states (where `get` re-serialises Rust state through serde and
    /// the cache cuts the cost down to one allocation per trigger
    /// cycle). Override to `false` for "derived" scopes whose `get`
    /// reads through to a parent proxy — `SlotScope`'s `ctx` ident
    /// composes a fresh JS object from the owner's current field
    /// values on each call, so caching it would freeze the slot at
    /// its first-render snapshot even after the owner mutates.
    fn cacheable_fields(&self) -> bool {
        true
    }

    /// Whether `key` names a `#[computed]` synthetic field. Computed
    /// fields carry their own memoization (a `Computed<JsValue>` with
    /// a dirty bit) and re-run reactively through their own signal, so
    /// they must NOT also be held in the per-signal projection cache:
    /// that cache is keyed on — and only invalidated by — a write to
    /// the field itself, but a computed is never written directly. A
    /// cached projection of a computed would therefore go stale the
    /// moment an upstream dependency changed, masking the recompute
    /// (see `read_field_tracked`). Defaults to `false`; the
    /// `#[component]` macro overrides it to consult `computed_keys()`.
    fn is_computed_field(&self, key: &str) -> bool {
        let _ = key;
        false
    }

    /// Write a declared field from a JsValue (for proxy `set`).
    fn set(&mut self, key: &str, value: JsValue);

    /// All data keys this component exposes. Used for sweep-triggers after
    /// a handler invocation.
    fn keys(&self) -> &'static [&'static str];

    /// RFC-095 W2 — 64-bit dirty-check fingerprint of one declared
    /// field's current value, computed entirely Rust-side (serde →
    /// [`crate::fingerprint`], no bridge crossing). The per-field
    /// dirty sweep snapshots observed fields around a handler and
    /// triggers only the ones whose fingerprints moved.
    ///
    /// `None` means "unknown" — computed fields, flatten leaves,
    /// non-field keys, derived scopes. The sweep treats unknown as
    /// *changed*, so a `None` can only over-trigger (the pre-sweep
    /// status quo), never miss an update.
    fn field_fingerprint(&self, key: &str) -> Option<u64> {
        let _ = key;
        None
    }

    /// RFC-095 W2b — O(1) length probe of one declared field
    /// (`Some(len)` for collection-shaped fields, `None`
    /// otherwise — see [`crate::fingerprint::quick_len`]). The
    /// dirty sweep short-circuits "changed" on a length move
    /// without hashing the contents; `None`/`None` falls through
    /// to the fingerprint compare, so the default is always
    /// correct, just slower for big collections.
    fn field_quick_len(&self, key: &str) -> Option<u64> {
        let _ = key;
        None
    }

    /// RFC-096 S3 — typed text projection of one declared field:
    /// `Some(string)` for serde-scalar fields (rendered exactly
    /// as `pp-text` would), `None` for compound fields and
    /// unknown keys (which take the JsValue-projection path).
    /// Zero serde-to-JS, zero `JsValue` on the `Some` path.
    fn field_as_text(&self, key: &str) -> Option<String> {
        let _ = key;
        None
    }

    /// RFC-031 — is `key` annotated `#[prop]`? Returns `false` for
    /// state fields (the default — anything not explicitly
    /// marked as part of the parent contract). Used by
    /// `apply_static_props`, `pp-bind`'s child-prop write, and
    /// `pp-model`'s mirror-in leg to keep parents out of state.
    /// Unknown keys return `false` — the runtime also uses
    /// `keys()` / `set()` to know which fields exist at all.
    fn is_prop(&self, key: &str) -> bool {
        let _ = key;
        false
    }

    /// Coercion hint for static HTML attrs targeting `#[prop]`
    /// fields. Unknown and flattened props use `Auto`, preserving the
    /// pre-existing generic coercion path.
    fn static_prop_kind(&self, key: &str) -> StaticPropKind {
        let _ = key;
        StaticPropKind::Auto
    }

    /// RFC-044 §5.10 — for a `flatten` leaf key, the container field
    /// key it writes through; `None` for ordinary keys. A write to a
    /// flattened leaf mutates the *whole* container field, so the
    /// proxy `set` trap triggers both the leaf key and the container
    /// key — that is what lets a single `#[watch(<container>)]` fire
    /// when any one leaf changes. Defaults to `None` so non-component
    /// scopes and flatten-free components need no override.
    fn flatten_container_of(&self, key: &str) -> Option<&'static str> {
        let _ = key;
        None
    }

    /// True iff `key` is a `#[model]` field. Runtime uses this for
    /// assignment-driven model publication and devtools metadata.
    fn is_model(&self, key: &str) -> bool {
        let _ = key;
        false
    }

    /// Public wire name reserved by a `#[model]` field. Returns `None`
    /// for non-model keys.
    fn model_name(&self, key: &str) -> Option<&'static str> {
        let _ = key;
        None
    }

    /// Serialize a model field with any field-level serde attrs still
    /// in play. Defaults to the plain field getter so non-component
    /// scopes keep compiling.
    fn get_model_value(&self, key: &str) -> JsValue {
        self.get(key)
    }

    /// Invoke a named method on `&mut self` with JS-land arguments.
    /// Returns a JsValue (or `JsValue::UNDEFINED` for void methods).
    fn invoke(&mut self, key: &str, args: &Array) -> JsValue;

    /// RFC-097 §3.3 — does the handler named `key` take `&self` (an
    /// immutable receiver)? Such a handler provably cannot mutate
    /// component state, so [`Scope::invoke`] skips the [`DirtySweep`]
    /// and model-write bracket for it. `#[component]`/`#[store]` delegate
    /// this to the receiver partition the `#[handlers]` macro computes;
    /// derived scopes keep the default (`false` → always swept).
    fn is_readonly_handler(&self, _key: &str) -> bool {
        false
    }

    /// Lifecycle — called once right after the scope is minted and
    /// its RFC-027 parent is set, *before* the template's children
    /// walk. Lets compound-component children initialise fields
    /// from injected context so directives in their template see
    /// the populated values on first bind. Default no-op;
    /// `#[component]` wires the user's `on_setup` when one exists.
    /// RFC 056 follow-on: receives a `LifecycleContext` (phase
    /// `Setup`) so authors can extract `Inject<KEY, T>`,
    /// `Handle<Self>`, etc. Element-dependent extractors panic in
    /// this phase (template hasn't been walked).
    fn setup(&mut self, ctx: crate::lifecycle::LifecycleContext<'_>) {
        let _ = ctx;
    }

    /// Lifecycle — called once after the component's subtree is fully
    /// bound. Default no-op; `#[component]` wires the user's
    /// `on_mount` when one exists. RFC-032: receives a
    /// `LifecycleContext` so handler signatures can extract the
    /// rendered root, scope id, refs, etc. via `From`.
    fn mount(&mut self, ctx: crate::lifecycle::LifecycleContext<'_>) {
        let _ = ctx;
    }

    /// Lifecycle — called once, scheduled via `tick::next` AFTER
    /// `mount()` returns. Takes `&self` (not `&mut self`) so
    /// proxy-reading code inside the hook (watches, refs, etc.)
    /// doesn't clash with the scope's state borrow. Mutation in
    /// on_ready goes through `pocopine::this::<Self>().defer_update(...)`.
    /// Default no-op; `#[component]` wires the user's `on_ready`
    /// when one exists. See RFC-026 / RFC-029 / RFC-032.
    fn on_ready(&self, ctx: crate::lifecycle::LifecycleContext<'_>) {
        let _ = ctx;
    }

    /// Lifecycle — called once just before the component is torn down.
    /// Default no-op; `#[component]` wires the user's `on_unmount`
    /// when one exists. RFC 056 follow-on: receives a
    /// `LifecycleContext` (phase `Unmount`) for symmetry with the
    /// other lifecycle hooks. Element-dependent extractors panic
    /// (the element may already be detaching).
    fn unmount(&mut self, ctx: crate::lifecycle::LifecycleContext<'_>) {
        let _ = ctx;
    }

    /// True iff the component has a user-defined `on_setup`.
    /// `mount_component` uses this to skip the setup call for
    /// components without the hook.
    fn has_setup(&self) -> bool {
        false
    }

    /// True iff the component actually has a user-defined `on_mount`.
    /// Lets the mount skip the post-mount `trigger_scope` sweep for
    /// components that don't need it — critical for recursive
    /// children, where a blanket sweep would cascade through the
    /// whole subtree.
    fn has_on_mount(&self) -> bool {
        false
    }

    /// True iff the component has a user-defined `on_ready` hook.
    /// Walker uses this to decide whether to schedule a microtask
    /// after mount — components without the hook pay nothing.
    fn has_on_ready(&self) -> bool {
        false
    }

    /// RFC-038 — enter preset name the component declared at
    /// `#[component(transition = "…")]` (or `transition_in`). The
    /// mount calls this once post-template-clone to stamp the
    /// preset's `pp-transition:*` attrs on the rendered root.
    fn transition_in_preset(&self) -> &'static str {
        ""
    }

    /// RFC-038 — leave preset name (`transition` or `transition_out`).
    fn transition_out_preset(&self) -> &'static str {
        ""
    }

    /// RFC-038 — keyed-pp-for layout-animation kind (only `"flip"`
    /// today). The mount's for_.rs hooks check this to decide
    /// whether to FLIP-animate reordered clones.
    fn animate_kind(&self) -> &'static str {
        ""
    }

    /// Human-readable tag / type name used by devtools. Default
    /// `"?"`; `#[component]` / `#[store]` override with the concrete
    /// kebab-case name.
    fn type_name(&self) -> &'static str {
        "?"
    }
}

/// A live component instance bound to a DOM element.
///
/// Holds both the type-erased `ComponentState` handle the mount uses and
/// a typed `Rc<RefCell<T>>` behind an `Any` for handler code that wants
/// to mutate the underlying Rust struct directly (see
/// [`crate::this`](crate::handle::this)).
#[derive(Clone)]
pub struct Scope {
    pub id: ScopeId,
    pub state: Rc<RefCell<dyn ComponentState>>,
    /// `Rc<RefCell<T>>` erased behind `dyn Any`. `T` is the concrete
    /// struct the user annotated with `#[component]` / `#[store]`.
    /// Downcast via [`Scope::typed`] to mutate Rust fields directly.
    pub typed: Rc<dyn Any>,
}

/// Type-erased storage for the two `Closure`s backing a proxy's
/// `get` and `set` traps. Kept as a `Vec<Box<dyn Any>>` so the
/// per-trap type parameters don't pollute the side-table's type.
/// Dropping the `Box<dyn Any>` drops the underlying `Closure`,
/// which reclaims the `Box<dyn Fn>` behind it — the whole point of
/// this table (old code called `.forget()` and leaked forever).
type AnyClosures = Vec<Box<dyn Any>>;

/// One projection slot per field signal — the RFC-096 S3 versioned
/// projection store, co-located so a read/store/invalidate touches one
/// map instead of two parallel ones keyed on the same `SignalId`.
/// `version` bumps on invalidate/confirm; `cached` holds the marshalled
/// value with the stamp it was stored at, and is live for a read iff
/// `stamp == version`.
#[derive(Default)]
struct ProjectionSlot {
    version: u32,
    cached: Option<(u32, JsValue)>,
}

/// One event callback constructed lazily only when its target component scope
/// is already inside a [`crate::ComponentCallbackFrame`].
type PendingInvocation = Box<dyn FnOnce()>;

thread_local! {
    /// Registry of live scopes keyed by id. Directives look up the scope
    /// here to invoke handlers when an event fires.
    static SCOPES: RefCell<HashMap<ScopeId, Scope>> = RefCell::new(HashMap::new());

    /// Proxy-trap closures pinned to their owning scope id. Previously
    /// these were leaked via `Closure::forget()` — the comment there
    /// claimed "live as long as the scope" but `Scope::remove` had no
    /// code path to recover them. With the side-table, `Scope::remove`
    /// drops the entry and the two `Box<dyn Fn>` boxes behind the
    /// closures are reclaimed.
    static PROXY_CLOSURES: RefCell<HashMap<ScopeId, AnyClosures>> =
        RefCell::new(HashMap::new());

    /// RFC 054 phase A — per-scope cache of serialised JS values
    /// for `ComponentState::get` results. The proxy's `get` trap
    /// reads this first; cache miss falls through to
    /// `state.get(key)` (which serialises the field via
    /// `serde_wasm_bindgen`) and stores the result so subsequent
    /// reads of the same field reuse the same `JsValue`. Targeted
    /// list ops (`patch_list_at`, etc.) update the cache + the
    /// underlying Rust state in lockstep so the cached `Array` /
    /// `Object` identities stay stable across mutations — pp-for
    /// row identity becomes a pointer comparison instead of a
    /// fresh JSON.stringify per row.
    ///
    /// Invalidation: `set` trap drops the slot for that key;
    /// `Handle::update` / `Scope::invoke` clear the whole scope's
    /// cache after the closure / handler runs (we don't know
    /// which fields it touched). Fields the handler explicitly
    /// kept fresh via `patch_list_at_inline` are recorded in
    /// the PATCHED set and survive invalidation by version re-stamp.
    /// RFC-096 S3 — versioned projections ON the field signal, now
    /// in one [`ProjectionSlot`] per signal (was two parallel maps,
    /// `VERSIONS` + `PROJECTIONS`, keyed on the same `SignalId`). A
    /// slot's `cached` value is valid iff its stamp equals the slot's
    /// current `version` (default 0). Invalidation is a version bump
    /// that clears `cached`; the old FIELD_CACHE map-removal dance and
    /// the FRESH_FIELDS survive-the-blanket set are both subsumed
    /// (PATCHED marks a projection the `patch_*` APIs kept correct
    /// through a mutation — the sweep re-stamps it to the new version
    /// instead of dropping it).
    static PROJECTIONS: RefCell<HashMap<SignalId, ProjectionSlot>> =
        RefCell::new(HashMap::new());
    static PATCHED: RefCell<HashMap<ScopeId, std::collections::HashSet<SignalId>>> =
        RefCell::new(HashMap::new());
    /// RFC-096 S3 — debug/devtools counter: serde projections
    /// built (one per cache-miss field read). The S3 acceptance
    /// gate asserts this stays flat on scalar-change paths once
    /// the typed lane covers them.
    #[cfg(any(debug_assertions, feature = "devtools"))]
    static SERDE_PROJECTIONS: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };

    /// RFC-097 §6 — debug/devtools counter: field fingerprints computed
    /// (every observed field, twice per swept `Handle::update`/handler
    /// dispatch). The acceptance gate asserts this stays flat across a
    /// `FieldHandle::set` and a `&self` handler invocation — both of
    /// which deliberately run no [`DirtySweep`].
    #[cfg(any(debug_assertions, feature = "devtools"))]
    static FINGERPRINTS: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };

    /// The element the current directive is running against. Set by the
    /// mount immediately around each directive call so `$el` works without
    /// threading the element through every call site.
    static CURRENT_EL: RefCell<Option<Element>> = const { RefCell::new(None) };

    /// The scope whose handler is currently executing, if any. Set by
    /// `Scope::invoke` for the duration of the call so handlers can
    /// discover their own id — useful when a handler needs to capture the
    /// id for an `async` task that will mutate the scope after the
    /// handler returns.
    static CURRENT_SCOPE_ID: std::cell::Cell<Option<ScopeId>> =
        const { std::cell::Cell::new(None) };

}

/// Queue a browser event expression when a handler for the same scope is still
/// holding the component's mutable borrow. Returns whether it queued the task.
/// The factory runs only on the re-entrant path so ordinary events do not clone
/// their element, AST, proxy, and event solely to build an unused closure.
///
/// Queueing the complete expression (rather than only its first handler call)
/// also keeps reads, assignments, and multi-statement expressions away from
/// the active `RefCell` borrow. The outermost component callback frame drains
/// it synchronously after every nested component borrow has unwound.
pub(crate) fn queue_event_expression_if_active(
    scope_id: ScopeId,
    task: impl FnOnce() -> PendingInvocation,
) -> bool {
    if crate::component_callback::scope_is_active(scope_id) {
        crate::defer_component_callback_for(scope_id, task());
        true
    } else {
        false
    }
}

impl Scope {
    /// Build a scope from a typed `Rc<RefCell<T>>`. Stashes both the
    /// type-erased and the typed form so later code (mount + handler
    /// handles) can choose the right one.
    pub fn new<T: ComponentState + 'static>(state: Rc<RefCell<T>>) -> Self {
        let id = next_scope_id();
        let erased: Rc<RefCell<dyn ComponentState>> = state.clone();
        // RFC-101 P4 — erase `state` straight to `Rc<dyn Any>` via an
        // unsizing coercion (a fat-pointer rebind, no heap block)
        // instead of `Rc::new(state)`, which boxed the already-`Rc`
        // state inside a SECOND `Rc` purely to satisfy `Any`. Saves one
        // allocation per scope mint — per pp-for row, on the hot path.
        // `typed()` now recovers it with `Rc::downcast` (see below).
        let typed: Rc<dyn Any> = state;
        let scope = Scope {
            id,
            state: erased,
            typed,
        };
        SCOPES.with(|s| s.borrow_mut().insert(id, scope.clone()));
        scope
    }

    /// Look up a live scope by id.
    pub fn find(id: ScopeId) -> Option<Scope> {
        SCOPES.with(|s| s.borrow().get(&id).cloned())
    }

    /// Snapshot of every live scope, sorted by id. Devtools reads this
    /// to render the scope list.
    pub fn all() -> Vec<Scope> {
        SCOPES.with(|s| {
            let mut out: Vec<Scope> = s.borrow().values().cloned().collect();
            out.sort_by_key(|sc| sc.id.0);
            out
        })
    }

    /// Live scope count — a cheap health counter for tests/devtools (the
    /// registry-side sibling of `reactive::stats`). Compiled rows have no
    /// per-row effects, so a leaked LoopScope is invisible to the effect
    /// counter; this is the metric that catches it.
    #[cfg(any(debug_assertions, feature = "devtools"))]
    pub fn count() -> usize {
        SCOPES.with(|s| s.borrow().len())
    }

    /// Remove a scope from the registry. Called when its element is
    /// unmounted. Also drops any refs + captured slot content
    /// registered against this scope so we don't leak element
    /// handles.
    pub fn remove(id: ScopeId) {
        SCOPES.with(|s| s.borrow_mut().remove(&id));
        crate::refs::clear_scope(id);
        crate::mount::clear_light_dom_slots(id);
        crate::slot_fragment::clear(id);
        crate::context::clear_scope(id);
        crate::events::clear_scope(id);
        crate::reactive::clear_scope(id);
        crate::component_computed::clear_scope(id);
        crate::model_runtime::clear_scope(id);
        crate::lifecycle::__clear_mount_epoch(id);
        crate::task::clear_scope(id);
        // Drop the proxy-trap closures that were pinned in
        // `into_proxy`. The `Box<dyn Any>` drop chain runs the
        // `Closure` destructor, which releases the underlying
        // `Box<dyn Fn>`.
        PROXY_CLOSURES.with(|m| {
            m.borrow_mut().remove(&id);
        });
        PATCHED.with(|f| {
            f.borrow_mut().remove(&id);
        });
        BRIDGES.with(|b| {
            b.borrow_mut().remove(&id);
        });
        // Projection storage is purged inside `reactive::clear_scope`
        // (it drains the interned signal ids).
    }

    /// Bulk teardown for the RFC 054 compiled-row bulk-clear path.
    /// Drains every per-scope side-table once over the full slice
    /// instead of paying `12 × thread_local::with` per scope.
    /// Compiled row scopes are guaranteed not to register
    /// refs/slots/tasks/inject/computed/model state — those
    /// table-clears collapse to a no-op for known-empty maps.
    ///
    /// **Caller obligations:** every id in `ids` MUST be a
    /// compiled-row loop scope. General-purpose scope teardown
    /// still goes through [`Scope::remove`].
    pub fn remove_compiled_rows(ids: &[ScopeId]) {
        if ids.is_empty() {
            return;
        }
        SCOPES.with(|s| {
            let mut map = s.borrow_mut();
            for id in ids {
                map.remove(id);
            }
        });
        crate::context::clear_scopes(ids);
        crate::reactive::clear_scopes(ids);
        // Compiled rows that never minted a proxy have no entry in
        // PROXY_CLOSURES / PATCHED — the
        // per-id `remove` is a hash + compare with no value drop.
        // Still cheaper than 10K thread_local::with calls.
        PROXY_CLOSURES.with(|m| {
            let mut map = m.borrow_mut();
            if !map.is_empty() {
                for id in ids {
                    map.remove(id);
                }
            }
        });
        // RFC-096 S4 — js_bridge proxies minted over row scopes
        // must die with the scope, or the cached bridge keeps
        // re-interning reactive state for a dead ScopeId.
        BRIDGES.with(|m| {
            let mut map = m.borrow_mut();
            if !map.is_empty() {
                for id in ids {
                    map.remove(id);
                }
            }
        });
        PATCHED.with(|f| {
            let mut map = f.borrow_mut();
            if !map.is_empty() {
                for id in ids {
                    map.remove(id);
                }
            }
        });
        // Projection storage rides `reactive::clear_scopes` above.
        crate::lifecycle::__clear_mount_epochs(ids);
    }

    /// Recover the typed inner `Rc<RefCell<T>>`, if `T` matches the struct
    /// this scope was created with. `None` on type mismatch.
    pub fn typed<T: 'static>(&self) -> Option<Rc<RefCell<T>>> {
        // RFC-101 P4 — `typed` now stores the state's own
        // `Rc<RefCell<T>>` erased as `Rc<dyn Any>` (no double-Rc), so
        // recover it by downcasting the `Rc` itself. Returns `None` on
        // type mismatch, exactly as the old `downcast_ref` did.
        self.typed.clone().downcast::<RefCell<T>>().ok()
    }

    /// Build a `js_sys::Proxy` whose `get` trap records dependencies and
    /// whose `set` trap triggers them. The proxy is what every directive
    /// reads through.
    pub fn into_proxy(&self) -> JsValue {
        Self::mint_proxy(self.id, &self.state)
    }
}

/// RFC-095 W1 — the tracked-read core shared by the proxy `get`
/// trap and [`scoped_root_reader`]: track the dependency, honor
/// `cacheable_fields`, serve from / populate the projection store,
/// fall through to `ComponentState::get`. One implementation so
/// the proxy path and the proxy-free path cannot diverge.
fn read_field_tracked(
    scope_id: ScopeId,
    state: &Rc<RefCell<dyn ComponentState>>,
    key: &str,
) -> JsValue {
    track(scope_id, key);
    // Derived scopes (`SlotScope`, etc.) compose their return value
    // from a parent proxy on every read — caching would freeze the
    // value at the first call. Skip the cache lookup AND the cache
    // write for those; the trigger that matters lands on the parent
    // scope's key, picked up via the inner `Reflect::get` inside
    // `state.get`.
    let cacheable = state.borrow().cacheable_fields();
    if !cacheable {
        return state.borrow().get(key);
    }
    // A `#[computed]` field is memoized by its own `Computed<JsValue>`
    // (dirty bit + cached value) and re-runs through its own signal,
    // which the `get` below subscribes the current effect to. Layering
    // the projection cache on top would freeze it at its first value:
    // the projection is only invalidated by a write to `key`, but a
    // computed is never written — so an upstream change would recompute
    // the `Computed` yet keep serving the stale projection. Read
    // straight through; the computed's own cache is the memoization.
    if state.borrow().is_computed_field(key) {
        return state.borrow().get(key);
    }
    // RFC 054 phase A — field cache short-circuit. The first `get`
    // for a field invokes the macro-emitted `ComponentState::get`
    // (which serialises via `serde_wasm_bindgen`); subsequent reads
    // of the same field by other effects in the same trigger cycle
    // reuse the cached JsValue. Targeted `patch_*` ops keep the
    // cache valid across mutations so Vec fields don't pay the full
    // re-serialise tax on every reactive cycle.
    if let Some(cached) = projection_read(scope_id, key) {
        return cached;
    }
    let v = state.borrow().get(key);
    count_serde_projection();
    projection_store(scope_id, key, v.clone());
    v
}

/// RFC-095 W1 / RFC-096 S1 — the [`crate::expr::ScopeAccess`]
/// over a component scope: reads via [`read_field_tracked`]
/// (track + cache + `ComponentState::get`, all Rust-side),
/// writes via [`write_field_tracked`] (the set trap's body).
/// `$`-prefixed names belong to the proxy trap on both sides.
struct ScopedFieldAccess {
    scope_id: ScopeId,
    state: Rc<RefCell<dyn ComponentState>>,
}

impl crate::expr::ScopeAccess for ScopedFieldAccess {
    fn read(&self, key: &str) -> Option<JsValue> {
        // RFC-096 S2 — $-roots resolve here too (loop locals,
        // magics): the access is read-complete, so the proxy
        // fallback is unreachable for reads.
        Some(read_scope_key_with(self.scope_id, &self.state, key))
    }
    fn write(&self, key: &str, value: &JsValue) -> bool {
        if key.starts_with('$') {
            return false;
        }
        write_field_tracked(self.scope_id, &self.state, key, value.clone());
        true
    }
}

/// Build a [`crate::expr::RootAccess`] for `scope_id` — root
/// reads AND writes resolve against the Rust state directly; no
/// proxy trap, no `Reflect`, no wasm→JS→wasm bounce. Returns
/// `None` when the scope is already gone — callers then evaluate
/// against the proxy alone, exactly the pre-W1 behavior.
pub fn scoped_root_reader(scope_id: ScopeId) -> Option<crate::expr::RootAccess> {
    let scope = Scope::find(scope_id)?;
    Some(Rc::new(ScopedFieldAccess {
        scope_id,
        state: scope.state,
    }))
}

/// RFC-096 S3 — the typed text lane's tracked read: subscribe,
/// then extract the scalar string straight from Rust state.
/// `None` (scope gone) → caller bails; `Some(None)` (compound or
/// unknown field) → caller falls back to the JsValue projection
/// path. No serde-to-JS on the scalar path.
pub(crate) fn read_field_text(scope_id: ScopeId, key: &str) -> Option<Option<String>> {
    let scope = Scope::find(scope_id)?;
    track(scope_id, key);
    let text = scope.state.borrow().field_as_text(key);
    Some(text)
}

/// RFC-096 S3 — projection-store primitives. Projections live on
/// the field's interned signal, stamped with the version current
/// at build time; a version bump is the invalidation.
fn projection_read(scope_id: ScopeId, field: &str) -> Option<JsValue> {
    let sid = crate::reactive::ensure_field_signal(scope_id, field);
    // One map lookup (was two): the cached value is live iff its stamp
    // still equals the slot's current version.
    PROJECTIONS.with(|p| {
        p.borrow().get(&sid).and_then(|slot| {
            slot.cached
                .as_ref()
                .filter(|(stamp, _)| *stamp == slot.version)
                .map(|(_, js)| js.clone())
        })
    })
}

fn projection_store(scope_id: ScopeId, field: &str, js: JsValue) {
    let sid = crate::reactive::ensure_field_signal(scope_id, field);
    PROJECTIONS.with(|p| {
        let mut p = p.borrow_mut();
        let slot = p.entry(sid).or_default();
        let ver = slot.version;
        slot.cached = Some((ver, js));
    });
}

fn projection_invalidate(sid: SignalId) {
    PROJECTIONS.with(|p| {
        let mut p = p.borrow_mut();
        let slot = p.entry(sid).or_default();
        slot.version += 1;
        slot.cached = None;
    });
}

/// A `patch_*` API kept this projection correct through the
/// mutation: bump the version AND re-stamp the (already correct)
/// projection so it survives, instead of dropping it.
fn projection_confirm_patched(sid: SignalId) {
    PROJECTIONS.with(|p| {
        let mut p = p.borrow_mut();
        let slot = p.entry(sid).or_default();
        slot.version += 1;
        let ver = slot.version;
        if let Some((stamp, _)) = slot.cached.as_mut() {
            *stamp = ver;
        }
    });
}

