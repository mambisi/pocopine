#!/usr/bin/env node
// Extract the class-candidate corpus from Tailwind's own test suite to
// use as a *grammar* oracle for Pine Stylekit's parser (RFC 092 D3).
//
// Tailwind's tests drive their compiler with `run([...])` / `compile([...])`
// arrays of class candidates. We don't byte-match Tailwind's CSS output
// ("shaped, not compatible"), but their candidate vocabulary is the best
// real-world corpus for proving `parse_class` never panics and splits
// variants/arbitrary values the way humans and LLMs expect.
//
// Source clone lives in tmp/tailwind (git-ignored). Run:
//   node scripts/extract-tailwind-candidates.mjs
// Regenerates crates/pocopine-stylekit/tests/fixtures/tailwind-candidates.txt
// (committed, so the oracle is reproducible without the clone).

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = resolve(ROOT, 'tmp/tailwind/packages/tailwindcss/src')
const OUT = resolve(ROOT, 'crates/pocopine-stylekit/tests/fixtures/tailwind-candidates.txt')

const FILES = ['utilities.test.ts', 'variants.test.ts', 'candidate.test.ts']

if (!existsSync(SRC)) {
  console.error(`tmp/tailwind clone not found at ${SRC}`)
  console.error('Clone it first: git clone --depth 1 https://github.com/tailwindlabs/tailwindcss.git tmp/tailwind')
  process.exit(1)
}

const candidates = new Set()
// Pull every `run([...])` / `compile([...])` array, then every quoted
// string token inside it.
const arrayRe = /\b(?:run|compile)\(\s*\[([\s\S]*?)\]/g
const tokenRe = /'([^'\n]+)'|"([^"\n]+)"/g

for (const file of FILES) {
  const text = readFileSync(resolve(SRC, file), 'utf8')
  for (const [, body] of text.matchAll(arrayRe)) {
    for (const m of body.matchAll(tokenRe)) {
      const tok = m[1] ?? m[2]
      // Skip CSS/template fragments and interpolation — we want bare
      // class candidates only.
      if (!tok || /[\s{}<>${}]/.test(tok)) continue
      candidates.add(tok)
    }
  }
}

const sorted = [...candidates].sort()
const header = `# Generated by scripts/extract-tailwind-candidates.mjs — do not edit by hand.
# Tailwind class-candidate corpus (grammar oracle for parse_class, RFC 092 D3).
# ${sorted.length} unique candidates.
`
writeFileSync(OUT, header + sorted.join('\n') + '\n')
console.log(`wrote ${sorted.length} candidates -> ${OUT}`)
