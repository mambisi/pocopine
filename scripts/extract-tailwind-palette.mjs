#!/usr/bin/env node
// Generate Pine Stylekit's default colour palette from Tailwind's
// theme.css (issue #172, RFC 092 M2). We ship Tailwind's exact default
// values (oklch) for the 22 canonical families so migrating users and
// LLMs get the colours they expect — `bg-slate-700` resolves without a
// @theme entry.
//
// Source clone lives in tmp/tailwind (git-ignored). Run:
//   node scripts/extract-tailwind-palette.mjs
// Regenerates crates/pocopine-stylekit/src/palette.rs (committed).

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const THEME = resolve(ROOT, 'tmp/tailwind/packages/tailwindcss/theme.css')
const OUT = resolve(ROOT, 'crates/pocopine-stylekit/src/palette.rs')

// Tailwind's documented default palette families. Excludes non-standard
// entries that appear in the upstream theme (mauve/mist/olive/taupe).
const FAMILIES = new Set([
  'slate', 'gray', 'zinc', 'neutral', 'stone',
  'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal',
  'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose',
])

if (!existsSync(THEME)) {
  console.error(`tmp/tailwind clone not found at ${THEME}`)
  console.error('Clone it: git clone --depth 1 https://github.com/tailwindlabs/tailwindcss.git tmp/tailwind')
  process.exit(1)
}

const text = readFileSync(THEME, 'utf8')
const re = /^\s*--color-([a-z]+)-(\d+):\s*([^;]+);/gm
const entries = []
for (const [, family, shade, value] of text.matchAll(re)) {
  if (FAMILIES.has(family)) {
    entries.push([`${family}-${shade}`, value.trim()])
  }
}

// Sort by key with plain byte/lexicographic order so Rust's
// `str::cmp`-based binary_search over the same slice matches.
entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))

const rows = entries.map(([k, v]) => `    ("${k}", "${v}"),`).join('\n')
const out = `//! Tailwind's default colour palette (issue #172, RFC 092 M2).
//!
//! @generated by scripts/extract-tailwind-palette.mjs — do not edit by hand.
//! ${entries.length} colours across ${FAMILIES.size} families, exact upstream
//! oklch values. Sorted by name for binary search.

/// \`(name, css-value)\` pairs, sorted by name.
pub static PALETTE: &[(&str, &str)] = &[
${rows}
];

/// Look up a palette colour like \`slate-700\` → its CSS value.
pub fn lookup(name: &str) -> Option<&'static str> {
    PALETTE
        .binary_search_by(|(key, _)| (*key).cmp(name))
        .ok()
        .map(|i| PALETTE[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_colours_resolve() {
        assert!(lookup("slate-700").is_some());
        assert!(lookup("rose-500").is_some());
        assert!(lookup("sky-50").is_some());
    }

    #[test]
    fn unknown_colours_miss() {
        assert_eq!(lookup("slate-1234"), None);
        assert_eq!(lookup("brand-500"), None);
        assert_eq!(lookup("surface"), None);
    }

    #[test]
    fn table_is_sorted_for_binary_search() {
        assert!(PALETTE.windows(2).all(|w| w[0].0 < w[1].0));
    }
}
`
writeFileSync(OUT, out)
console.log(`wrote ${entries.length} palette colours -> ${OUT}`)
